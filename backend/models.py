# BUSES
# ============================================================

class Bus(Base):
    """
    Stores the latest known location and status of each bus.
    """

    __tablename__ = "buses"

    id = Column(
        Integer,
        primary_key=True,
        index=True,
    )

    bus_id = Column(
        String,
        unique=True,
        nullable=False,
        index=True,
    )

    latitude = Column(
        Float,
        nullable=False,
    )

    longitude = Column(
        Float,
        nullable=False,
    )

    # PostGIS geographic point
    location = Column(
        Geometry(
            geometry_type="POINT",
            srid=4326,
            spatial_index=True,
        ),
        nullable=False,
    )

    last_seen = Column(
        DateTime,
        default=datetime.utcnow,
        onupdate=datetime.utcnow,
        nullable=False,
    )

    is_active = Column(
        Boolean,
        default=True,
        nullable=False,
    )